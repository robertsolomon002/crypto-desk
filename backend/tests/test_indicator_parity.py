"""The Charts tab computes indicators in the browser (D40); this fixture pins them to the backend.

`frontend/src/lib/__fixtures__/indicators_parity.json` holds a synthetic random walk and the
backend's `indicators.custom` output for it. The Vitest parity test reads the same file. If the
backend math changes, this test fails until the fixture is regenerated with
`uv run python tests/test_indicator_parity.py` (and the TypeScript port updated to match).
"""

import datetime as dt
import json
import math
from pathlib import Path

from desk.analytics._frames import to_jsonable
from desk.analytics.indicators import IndicatorRequest, custom

try:
    from tests.analytics_fakes import random_daily
except ImportError:  # run as a script
    from analytics_fakes import random_daily  # type: ignore[no-redef]

FIXTURE = (
    Path(__file__).resolve().parents[2]
    / "frontend" / "src" / "lib" / "__fixtures__" / "indicators_parity.json"
)  # fmt: skip
REQUEST = IndicatorRequest(
    sma=(20, 50, 200), ema=(20, 50, 200), bollinger=(20, 2.0), rsi=14, macd=(12, 26, 9), band=True
)


def build() -> dict:
    # Starts on a Wednesday so the weekly band's partial first week and next-Monday shift are
    # exercised; 320 days covers SMA200 and the 20-week band.
    daily = random_daily(dt.date(2024, 1, 3), dt.date(2024, 11, 17), seed=40)
    frame = custom(daily, REQUEST)
    return {
        "note": "Synthetic data. Generated by backend/tests/test_indicator_parity.py; do not edit.",
        "request": {
            "sma": [20, 50, 200],
            "ema": [20, 50, 200],
            "bb": [20, 2.0],
            "rsi": 14,
            "macd": [12, 26, 9],
            "band": True,
        },
        "rows": to_jsonable(frame),
    }


def _close(a: object, b: object) -> bool:
    if isinstance(a, float) and isinstance(b, float):
        return math.isclose(a, b, rel_tol=1e-12, abs_tol=1e-12)
    return a == b


def test_fixture_is_current() -> None:
    committed = json.loads(FIXTURE.read_text(encoding="utf-8"))
    fresh = json.loads(json.dumps(build()))
    assert committed["request"] == fresh["request"]
    assert len(committed["rows"]) == len(fresh["rows"])
    for old, new in zip(committed["rows"], fresh["rows"], strict=True):
        assert old.keys() == new.keys()
        assert all(_close(old[k], new[k]) for k in old), (old["date"], old, new)


def test_fixture_covers_every_column() -> None:
    rows = json.loads(FIXTURE.read_text(encoding="utf-8"))["rows"]
    last = rows[-1]
    for col in ("sma200", "ema200", "bb20_2_upper", "rsi14", "macd12_26_9_hist", "sma20w",
                "ema21w"):  # fmt: skip
        assert isinstance(last[col], float), col  # warmed up by the last row


if __name__ == "__main__":
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(build(), separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"wrote {FIXTURE}")
